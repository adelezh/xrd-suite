"""Generate a small, deterministic synthetic example. No experimental inputs."""
from pathlib import Path
import argparse
import json
import numpy as np
from .peaks import pseudo_voigt
from .paths import data_dir

def generate(folder):
    from xrd_gui.processing import StableAzimuthalIntegrator
    from .io import Curve, write_curve
    from tifffile import imwrite
    import yaml
    folder=Path(folder)
    if any(folder.glob('**/*')):raise FileExistsError(f'Choose an empty example directory: {folder}')
    folder.mkdir(parents=True,exist_ok=True)
    ai=StableAzimuthalIntegrator(dist=.1,poni1=.0064,poni2=.0064,pixel1=.0001,pixel2=.0001,wavelength=1e-10)
    ai.save(str(folder/'synthetic.poni'))
    mask=np.zeros((128,128),dtype=np.uint8);mask[:2,:]=1
    np.save(folder/'mask.npy',mask)
    angle=ai.center_array((128,128),'2th_deg')
    for name in ('integration','dark_sub','meta'):(folder/name).mkdir()
    for i,center in enumerate((3.,3.03),1):
        x=np.linspace(1.5,5.,701+i*20)
        y=15+pseudo_voigt(x,80,center,.12,.35)
        meta={'source':f'synthetic scan {i}','unit':'2th_deg','wavelength_m':1e-10,'synthetic':True,'expected_center':center,'expected_fwhm':.12,'expected_area':80}
        curve=Curve(x,y,np.sqrt(np.maximum(y,1)),meta)
        write_curve(folder/'integration'/f'synthetic_primary-{i}_mean_tth.chi',curve)
        write_curve(folder/f'peak-{i}.xye',curve)
        q=4*np.pi*np.sin(np.radians(x)/2)
        write_curve(folder/'integration'/f'synthetic_primary-{i}_mean_q.chi',Curve(q,y,None,dict(meta,unit='q_A^-1')))
        image=15+pseudo_voigt(angle,80,center,.12,.35)
        image[25:28,60:63]+=2000
        imwrite(folder/'dark_sub'/f'synthetic_primary-dk_sub_image-{i-1:05d}.tiff',image.astype('float32'))
    params={'Distance':.1,'Poni1':.0064,'Poni2':.0064,'Rot1':0.,'Rot2':0.,'Rot3':0.,'Wavelength':1e-10,'Detector':'Detector','Detector_config':{'pixel1':.0001,'pixel2':.0001,'max_shape':[128,128]}}
    (folder/'meta/synthetic.yaml').write_text(yaml.safe_dump({'calibration_md':params}))
    (folder/'README.txt').write_text('Synthetic, redistributable example generated by xrd_suite.example.\nLoad synthetic.poni and mask.npy; add dark_sub TIFFs; use 120 radial bins.\nAnalysis: import peak-1.xye and peak-2.xye; fit region 2.5 to 3.5, baseline none.\nExpected centers 3.0 / 3.03 degrees, FWHM 0.12, area 80.\nMonitor: choose integration as watched folder, display 1.5 to 5 degrees.\n')
    return folder

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=data_dir()/'synthetic example')
    options=parser.parse_args()
    if options.output.exists() and any(options.output.iterdir()):
        parser.error('Output already contains files; choose a new --output folder.')
    print(generate(options.output))

if __name__=='__main__':main()
